let lang = (localStorage.getItem("jam.lang") || (navigator.language || "en")).toLowerCase().startsWith("zh") ? "zh" : "en";
const q = new URLSearchParams(location.search).get("lang");
if (q === "zh" || q === "en") lang = q;

export const getLang = () => lang;
export function setLang(l) { lang = l; localStorage.setItem("jam.lang", l); document.documentElement.lang = l === "zh" ? "zh-CN" : "en"; }
export function t(key, vars) {
  const path = key.split(".");
  let v = path.reduce((o, k) => (o ? o[k] : undefined), S[lang]);
  if (v === undefined) v = path.reduce((o, k) => (o ? o[k] : undefined), S.en);
  if (v === undefined) return key;
  return vars ? String(v).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? "")) : v;
}
document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
